/**
 * Compiles the stylesheet that generated websites ship with.
 *
 * Published sites used to pull Tailwind from its play CDN as a <script> that
 * compiles CSS in the visitor's browser. Three problems with that:
 *
 *  - The play CDN is explicitly not for production.
 *  - Styling arrives only after a third-party script downloads and runs, so
 *    the page flashes unstyled and breaks entirely if the CDN is unreachable.
 *  - It forces the preview iframe to allow scripts, which gives the document
 *    an opaque origin — and an opaque origin cannot load images from a private
 *    address, so every generated photo silently failed to paint.
 *
 * Instead the utilities are compiled once, here, against the renderer itself
 * (its class vocabulary is fixed — it comes from our template strings, not
 * from the model) and inlined into every document.
 *
 *   npm run build:css
 */
import { execFileSync } from 'child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'fs';
import { tmpdir } from 'os';
import { join, resolve } from 'path';

const ROOT = resolve(__dirname, '..');
const RENDERER = join(ROOT, 'src', 'modules', 'website', 'website-renderer.service.ts');
const OUT = join(ROOT, 'src', 'modules', 'website', 'website-utilities.css.ts');
// Invoke the CLI's JS entry with node rather than the .bin shim: the shim
// goes through a shell, and the repository path contains a space.
const TAILWIND_CLI = resolve(
  ROOT, '..', 'frontend', 'node_modules', 'tailwindcss', 'lib', 'cli.js',
);

function main() {
  const work = mkdtempSync(join(tmpdir(), 'ngmia-css-'));
  try {
    const config = join(work, 'tailwind.config.js');
    const input = join(work, 'input.css');
    const output = join(work, 'output.css');

    // Scan the renderer's source: every class a generated site can carry is
    // written literally in there.
    writeFileSync(
      config,
      `module.exports = {
  content: [${JSON.stringify(RENDERER)}],
  corePlugins: { preflight: false },
  theme: { extend: {} },
};
`,
      'utf8',
    );
    writeFileSync(input, '@tailwind utilities;\n', 'utf8');

    execFileSync(
      process.execPath,
      [TAILWIND_CLI, '-c', config, '-i', input, '-o', output, '--minify'],
      { stdio: 'pipe' },
    );

    const css = readFileSync(output, 'utf8').trim();
    if (css.length < 500) {
      throw new Error(`CSS suspicieusement court (${css.length} octets)`);
    }

    writeFileSync(
      OUT,
      `/**
 * Generated by scripts/build-website-css.ts — do not edit by hand.
 *
 * The Tailwind utilities every generated site uses, compiled from the
 * renderer's own class vocabulary and inlined so a published page needs no
 * third-party script to look like itself. Re-run \`npm run build:css\` after
 * changing the classes in website-renderer.service.ts.
 */
export const WEBSITE_UTILITIES_CSS = ${JSON.stringify(css)};
`,
      'utf8',
    );

    const rules = (css.match(/\{/g) || []).length;
    console.log(`ok ${(css.length / 1024).toFixed(1)} Ko, ~${rules} regles -> ${OUT}`);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

main();
